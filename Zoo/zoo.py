def show_animal(index, animals):
    """Выводит животное по индексу"""
    if 0 <= index < len(animals):
        print(animals[index])
    else:
        print(f"No habitat with index {index}. Try 0..{len(animals)-1} or 'exit'.")


def main():
    """Этап 4 — бесконечный цикл с возможностью выхода"""
    animals = get_animals()
    greeting()
    while True:
        user_input = input("\nPlease enter the number of the habitat you would like to view: ")
        if user_input.strip().lower() == "exit":
            print("See you later!")
            break
        try:
            index = int(user_input)
            show_animal(index, animals)
        except ValueError:
            print("Please enter a valid number (0–5) or 'exit'.")


if __name__ == "__main__":
    main()

